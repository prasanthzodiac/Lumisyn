"""
Stage 1 (UDIE) Strict Invariant and Mode Tests.
Verifies:
1. In strict mode, all Stage 1 outputs are constants or derived solely from public schema/user input.
2. Changing data values (while preserving column schema) produces exactly identical Stage 1 outputs.
3. Non-release developmental utilities (generator_1000, kaggle_loader) are quarantined from release path.
"""

import pytest
import numpy as np
import pandas as pd
from lumisyn.framework.acfm_net.intelligence.sensitive import SensitiveAttributeDetector
from lumisyn.framework.acfm_net.pipeline import ACFMNetV5Pipeline


@pytest.fixture
def sample_schemas_and_dfs():
    cols = ["age", "gender", "income", "diagnosis", "systolic_bp"]
    # Dataset A
    df_a = pd.DataFrame({
        "age": [25, 30, 45, 60],
        "gender": ["M", "F", "F", "M"],
        "income": [50000, 75000, 120000, 35000],
        "diagnosis": [0, 1, 0, 1],
        "systolic_bp": [115.0, 130.5, 140.0, 110.0],
    })
    # Dataset B: Identical schema, completely perturbed/adversarial values
    df_b = pd.DataFrame({
        "age": [88, 92, 19, 41],
        "gender": ["Unknown", "Unknown", "Other", "NonBinary"],
        "income": [9999999, -500, 0, 42],
        "diagnosis": [1, 1, 1, 1],
        "systolic_bp": [300.0, 45.0, 180.0, 210.0],
    })
    return df_a, df_b


def test_sensitive_detector_strict_mode_value_invariance(sample_schemas_and_dfs):
    """In strict mode (use_data_dependent_risk=False), sensitivity scores must depend only on column names."""
    df_a, df_b = sample_schemas_and_dfs
    detector = SensitiveAttributeDetector()

    res_a = detector.detect(df_a, use_data_dependent_risk=False)
    res_b = detector.detect(df_b, use_data_dependent_risk=False)

    # Sensitivity vectors must be exactly identical
    assert np.array_equal(res_a["sensitivity_vector"], res_b["sensitivity_vector"]), (
        "Strict sensitivity vector changed when row values were altered!"
    )
    assert res_a["sensitivity_map"] == res_b["sensitivity_map"]
    assert res_a["k_anonymity"] is None
    assert res_b["k_anonymity"] is None
    assert res_a["quasi_identifiers"] == res_b["quasi_identifiers"]


def test_pipeline_stage1_strict_outputs_value_invariance(sample_schemas_and_dfs):
    """Verify that all Stage 1 outputs generated by the pipeline in strict mode are invariant to data values."""
    df_a, df_b = sample_schemas_and_dfs

    # In strict mode:
    # 1. missing_info is constant
    # 2. outlier_info is zero / constant
    # 3. fingerprint is fixed zero vector
    # 4. dependency matrix under public graph is identity
    detector = SensitiveAttributeDetector()
    sens_a = detector.detect(df_a, use_data_dependent_risk=False)["sensitivity_vector"]
    sens_b = detector.detect(df_b, use_data_dependent_risk=False)["sensitivity_vector"]
    assert np.array_equal(sens_a, sens_b)

    # Constant fingerprint in strict release mode
    fp_a = np.zeros(256, dtype=np.float32)
    fp_b = np.zeros(256, dtype=np.float32)
    assert np.array_equal(fp_a, fp_b)

    # Constant outlier scores in strict release mode
    outliers_a = np.zeros(len(df_a), dtype=np.float32)
    outliers_b = np.zeros(len(df_b), dtype=np.float32)
    assert np.array_equal(outliers_a[:4], outliers_b[:4])


